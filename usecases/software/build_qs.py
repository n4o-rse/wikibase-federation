#!/usr/bin/env python3
"""
Generate input.qs for the software use case from model.py.

For every subject item and every statement:
  - always emit the LOCAL property line (predicate = local PID);
  - if PROPERTY_MODE == "local+federated" AND the property has a Wikidata
    equivalent whose datatype is NOT url, also emit a FEDERATED line
    (predicate = wd:P...). url-typed federated duplicates are skipped because
    the url datatype is blocked on this instance.

Item values are written as federated Wikidata items (wd:Q...) when
USE_FEDERATED_VALUES is true; otherwise those statements are deferred.

Run:
    python usecases\\software\\build_qs.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import model  # noqa: E402

WD = model.WD


def _prop_by_key(key: str) -> dict:
    for p in model.LOCAL_PROPERTIES:
        if p["key"] == key:
            return p
    return {}


def _value_columns(st) -> tuple[str, str] | None:
    """Return (value, datatype_token) for the QS line, or None if deferred."""
    if st.value_kind == "item":
        if not model.USE_FEDERATED_VALUES:
            return None
        return f"{WD}{st.value}", ""            # 3-col item (federated value)
    if st.value_kind == "string":
        return str(st.value), "string"
    if st.value_kind == "external_id":
        return str(st.value), "external-id"
    return None


def build(pid_map: dict[str, str], items: dict[str, str]) -> tuple[list[str], list[str]]:
    lines: list[str] = [
        "# Software use case - generated by build_qs.py from model.py",
        f"# PROPERTY_MODE={model.PROPERTY_MODE}  USE_FEDERATED_VALUES={model.USE_FEDERATED_VALUES}",
        "# Do not edit by hand; edit model.py and regenerate.",
        "",
    ]
    deferred: list[str] = []

    for item in model.ITEMS:
        qid = items.get(item.key)
        lines.append(f"# === {item.key} ({qid or 'NOT CREATED'}) ===")
        if not qid:
            deferred.append(f"item {item.key}: not created yet (run create_items.py)")
            continue

        for st in item.statements:
            prop = _prop_by_key(st.prop)
            local_pid = pid_map.get(st.prop)
            cols = _value_columns(st)
            if cols is None:
                deferred.append(f"{item.key}/{st.prop}: item value needs USE_FEDERATED_VALUES")
                continue
            value, dt = cols

            # local line
            if local_pid:
                lines.append(f"# {item.key}: {st.prop} (local)")
                lines.append(f"{qid}\t{local_pid}\t{value}" + (f"\t{dt}" if dt else ""))
            else:
                deferred.append(f"{item.key}/{st.prop}: local property not created yet")

            # federated duplicate
            if (model.PROPERTY_MODE == "local+federated"
                    and prop.get("wd_equiv") and prop.get("wd_datatype") != "url"):
                wd = prop["wd_equiv"]
                lines.append(f"# {item.key}: {st.prop} (federated wd:{wd})")
                lines.append(f"{qid}\twd:{wd}\t{value}" + (f"\t{dt}" if dt else ""))
            elif model.PROPERTY_MODE == "local+federated" and prop.get("wd_datatype") == "url":
                deferred.append(
                    f"{item.key}/{st.prop}: federated wd:{prop['wd_equiv']} skipped (url blocked)"
                )

    return lines, deferred


def main(argv: list[str] | None = None) -> int:
    pid_map: dict[str, str] = {}
    items: dict[str, str] = {}
    pfile, ifile = HERE / "properties.json", HERE / "items.json"
    if pfile.is_file():
        pid_map = json.loads(pfile.read_text(encoding="utf-8"))
    if ifile.is_file():
        items = json.loads(ifile.read_text(encoding="utf-8"))

    lines, deferred = build(pid_map, items)
    out = HERE / "input.qs"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    emitted = sum(1 for ln in lines if ln and not ln.startswith("#"))
    print(f"Wrote {out}")
    print(f"  emitted:  {emitted} statement line(s)")
    print(f"  deferred: {len(deferred)}")
    for d in deferred:
        print(f"    - {d}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
