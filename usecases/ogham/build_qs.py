#!/usr/bin/env python3
"""
Generate the QuickStatements file for the Ogham use case from the frozen model.

Reproducible: reads usecases/ogham/model.py and writes usecases/ogham/input.qs.
No network needed for the item-valued statements. It emits the statements the
current importer already supports and reports which ones are deferred (and why),
so the file grows automatically as the importer gains url / monolingual /
coordinate / reference / qualifier support.

Run (Windows / VS Code, global Python):

    python usecases\\ogham\\build_qs.py

Optional flags:
    --all       also emit deferred statements as comments (for preview)
    --resolve   path to a JSON mapping {property_key: "P123"} produced by the
                property-creation step, to resolve @local property tokens
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

# Import the sibling model module regardless of current working directory.
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import model  # noqa: E402

DEFERRED_REASON = {
    "url": "needs importer url/string-value support",
    "monolingual": "needs importer monolingual-text support",
    "coordinate": "needs importer globe-coordinate support",
    "external_id": "needs importer string-value support + local PID",
}

# wd_equiv (e.g. "P31") -> local property key (e.g. "instance_of")
WD_TO_LOCAL = {p["wd_equiv"]: p["key"] for p in model.LOCAL_PROPERTIES if p.get("wd_equiv")}


def _value_line(hub: str, pred: str, st) -> str:
    """QS line for a given predicate token and the statement's value/kind."""
    if st.value_kind == "item":
        return f"{hub}\t{pred}\t{st.value}"
    if st.value_kind == "url":
        return f"{hub}\t{pred}\t{st.value}\turl"
    if st.value_kind == "external_id":
        return f"{hub}\t{pred}\t{st.value}\texternal-id"
    if st.value_kind == "coordinate":
        lat, lon = st.value
        return f"{hub}\t{pred}\t{lat},{lon}\tcoordinate"
    text, lang = st.value  # monolingual
    return f"{hub}\t{pred}\t{text}\tmonolingual@{lang}"


def _predicates(st, pid_map: dict[str, str]) -> list[tuple[str | None, str]]:
    """Return [(predicate_token_or_None, tag)] to emit for this statement."""
    if st.prop.startswith("@"):
        return [(pid_map.get(st.prop[1:]), "local")]
    if st.prop.startswith("wd:"):
        wd_pid = st.prop[3:]
        local_key = WD_TO_LOCAL.get(wd_pid)
        out: list[tuple[str | None, str]] = []
        if model.PROPERTY_MODE in ("local", "local+federated"):
            out.append((pid_map.get(local_key) if local_key else None, "local"))
        if model.PROPERTY_MODE in ("federated", "local+federated"):
            out.append((st.prop, "federated"))
        return out
    return [(st.prop, "local")]  # a bare local PID


def build(pid_map: dict[str, str], include_all: bool) -> tuple[list[str], list[str]]:
    lines: list[str] = [
        "# Ogham use case (CIIC 81) - generated by build_qs.py from model.py",
        f"# Hub item: {model.HUB_ITEM}  PROPERTY_MODE={model.PROPERTY_MODE}",
        "# Do not edit by hand; edit model.py and regenerate.",
        "",
    ]
    deferred: list[str] = []

    for st in model.STATEMENTS:
        if st.value_kind not in model.SUPPORTED_VALUE_KINDS_TODAY:
            deferred.append(f"#{st.n} {st.prop} [{st.value_kind}] - "
                            f"{DEFERRED_REASON.get(st.value_kind, 'unsupported')}  ({st.label})")
            continue
        for pred, tag in _predicates(st, pid_map):
            if pred is None:
                deferred.append(f"#{st.n} {st.prop} [{tag}] - local property not created yet  ({st.label})")
                continue
            lines.append(f"# {st.label} ({tag})")
            lines.append(_value_line(model.HUB_ITEM, pred, st))

    return lines, deferred


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Build input.qs for the Ogham use case.")
    ap.add_argument("--all", action="store_true", help="include deferred statements as comments")
    ap.add_argument("--resolve", type=Path, default=HERE / "properties.json",
                    help="JSON map {property_key: PID} from the property-creation step")
    args = ap.parse_args(argv)

    pid_map: dict[str, str] = {}
    if args.resolve and args.resolve.is_file():
        pid_map = json.loads(args.resolve.read_text(encoding="utf-8"))

    lines, deferred = build(pid_map, include_all=args.all)

    out = HERE / "input.qs"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    emitted = sum(1 for ln in lines if ln and not ln.startswith("#"))
    print(f"Wrote {out}")
    print(f"  emitted:  {emitted} statement(s)")
    print(f"  deferred: {len(deferred)} statement(s)")
    for d in deferred:
        print(f"    - {d}")
    if not pid_map:
        print("  note: no properties.json found -> local (@) properties are deferred.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())